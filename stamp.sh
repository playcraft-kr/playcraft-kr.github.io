#!/bin/bash
# Give app.css / app.js / account.js a new version tag so browsers fetch the fresh files after every change.
cd "$(dirname "$0")/preview" || exit 1
v=$(date +%Y%m%d%H%M%S)
sed -i '' -E "s/(app\.css|app\.js|account\.js)(\?v=[0-9]+)?\"/\1?v=$v\"/g" index.html
grep -oE '(app\.css|app\.js|account\.js)\?v=[0-9]+' index.html

# The site opens straight at zanycade.com/: make ../index.html from preview/index.html with paths for the top folder.
# (Never edit the top index.html by hand; change preview/index.html and run this script.)
sed -E -e 's#(href|src)="\.\./#\1="#g' \
       -e 's#(href|src)="(app\.css|app\.js|account\.js|manifest\.webmanifest)#\1="preview/\2#g' \
       -e 's#<!DOCTYPE html>#<!DOCTYPE html>\n<!-- Made by stamp.sh from preview/index.html. Do not edit this file. -->#' \
       index.html > ../index.html
echo "index.html (top) rebuilt from preview/index.html"
